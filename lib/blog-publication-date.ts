// Publication dates use the Korean office's calendar day. PostgreSQL returns
// timestamptz in UTC, so splitting at T incorrectly moves midnight KST back a day.
export function blogPublicationDate(value: string): string {
  if (/^\d{4}-\d{2}-\d{2}$/.test(value)) return value;
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Seoul', year: 'numeric', month: '2-digit', day: '2-digit',
  }).format(date);
}
